export function ArtifactPreviewDialog() {
  const artifactPreviewId = useUIStore((s) => s.artifactPreviewId);
  const setArtifactPreviewId = useUIStore((s) => s.setArtifactPreviewId);
  const artifact = useArtifactsStore((s) =>
    s.artifacts.find((a) => a.id === artifactPreviewId),
  );
  const removeArtifact = useArtifactsStore((s) => s.removeArtifact);

  const open = Boolean(artifact);

  return (
    <Dialog open={open} onOpenChange={(o) => !o && setArtifactPreviewId(null)}>
      <DialogContent className="sm:max-w-lg">
        {artifact && (
          <>
            <DialogHeader>
              <DialogTitle className="flex items-center gap-2.5 text-base">
                <span className="flex size-8 items-center justify-center rounded-lg bg-secondary text-muted-foreground">
                  {(() => {
                    const Icon = kindIcon(artifact.kind);
                    return <Icon className="size-4" />;
                  })()}
                </span>
                <span className="min-w-0">
                  <span className="block truncate">{artifact.name}</span>
                  <span className="mt-0.5 block text-[11.5px] font-normal text-muted-foreground">
                    {artifact.kind.toUpperCase()} · {formatBytes(artifact.size)} ·{" "}
                    {artifact.origin === "user" ? "Uploaded by you" : "Generated by agent"}
                    {artifact.conversationTitle
                      ? ` · in ${artifact.conversationTitle}`
                      : ""}
                  </span>
                </span>
              </DialogTitle>
              <DialogDescription className="sr-only">
                Preview of {artifact.name}
              </DialogDescription>
            </DialogHeader>

            <div className="scrollbar-thin max-h-[50vh] min-h-32 overflow-auto rounded-xl border border-border/60 bg-secondary/25 p-3">
              {artifact.dataUrl ? (
                <img
                  src={artifact.dataUrl}
                  alt={artifact.name}
                  className="mx-auto max-h-[46vh] rounded-lg object-contain"
                />
              ) : artifact.textContent ? (
                <pre className="whitespace-pre-wrap break-words font-mono text-[12px] leading-relaxed text-muted-foreground">
                  {artifact.textContent.slice(0, 10_000)}
                  {artifact.textContent.length > 10_000 && "\n\n… (truncated preview)"}
                </pre>
              ) : (
                <div className="flex h-36 flex-col items-center justify-center gap-2 text-center">
                  {(() => {
                    const Icon = kindIcon(artifact.kind);
                    return <Icon className="size-7 text-muted-foreground/50" />;
                  })()}
                  <p className="text-[12.5px] text-muted-foreground">
                    In-app preview for {artifact.kind.toUpperCase()} files is
                    coming soon.
                  </p>
                </div>
              )}
            </div>

            <div className="flex items-center justify-between gap-2">
              <Button
                variant="ghost"
                size="sm"
                className="h-8 gap-1.5 text-[12.5px] text-destructive hover:bg-destructive/10 hover:text-destructive"
                onClick={() => {
                  removeArtifact(artifact.id);
                  setArtifactPreviewId(null);
                  toast.success("Artifact removed");
                }}
              >
                <Trash2 className="size-3.5" /> Remove
              </Button>
              <Button
                size="sm"
                className="h-8 gap-1.5 rounded-full px-4 text-[12.5px]"
                onClick={() => downloadArtifact(artifact)}
              >
                <Download className="size-3.5" /> Download
              </Button>
            </div>
          </>
        )}
      </DialogContent>
    </Dialog>
  );
}

