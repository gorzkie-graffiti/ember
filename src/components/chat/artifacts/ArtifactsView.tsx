type Filter = "all" | "user" | "agent";

export function ArtifactsView() {
  const artifacts = useArtifactsStore((s) => s.artifacts);
  const removeArtifact = useArtifactsStore((s) => s.removeArtifact);
  const setArtifactPreviewId = useUIStore((s) => s.setArtifactPreviewId);
  const openChat = useChatStore((s) => s.openChat);
  const [filter, setFilter] = useState<Filter>("all");

  const filtered = useMemo(
    () =>
      artifacts
        .filter((a) => filter === "all" || a.origin === filter)
        .sort((a, b) => b.createdAt - a.createdAt),
    [artifacts, filter],
  );

  const counts = useMemo(
    () => ({
      all: artifacts.length,
      user: artifacts.filter((a) => a.origin === "user").length,
      agent: artifacts.filter((a) => a.origin === "agent").length,
    }),
    [artifacts],
  );

  return (
    <div className="scrollbar-thin min-h-0 flex-1 overflow-y-auto">
      <div className="mx-auto max-w-3xl px-4 py-6 sm:px-6">
        <header className="mb-6 flex items-start gap-2">
          <MobileNavButton />
          <div>
            <h1 className="flex items-center gap-2.5 text-xl font-semibold">
              <Boxes className="size-5 text-primary" /> Artifacts
            </h1>
            <p className="mt-1.5 text-[13.5px] leading-relaxed text-muted-foreground">
              Files you&apos;ve uploaded and files the agent has generated — all
              reviewable in one place, across your chats.
            </p>
          </div>
        </header>

        {/* Filters */}
        <div className="mb-4 flex items-center gap-1.5">
          {(
            [
              ["all", "All", counts.all],
              ["user", "Uploaded", counts.user],
              ["agent", "Generated", counts.agent],
            ] as Array<[Filter, string, number]>
          ).map(([key, label, count]) => (
            <button
              key={key}
              onClick={() => setFilter(key)}
              aria-pressed={filter === key}
              className={cn(
                "flex h-8 items-center gap-1.5 rounded-full px-3.5 text-[12.5px] font-medium transition-colors",
                filter === key
                  ? "bg-primary/12 text-primary"
                  : "text-muted-foreground hover:bg-secondary hover:text-foreground",
              )}
            >
              {label}
              <span className="text-[11px] opacity-70">{count}</span>
            </button>
          ))}
        </div>

        {/* List */}
        {filtered.length === 0 ? (
          <div className="flex flex-col items-center gap-3 rounded-2xl border border-dashed border-border px-6 py-14 text-center">
            <span className="flex size-11 items-center justify-center rounded-xl bg-secondary text-muted-foreground">
              <Boxes className="size-5" />
            </span>
            <div>
              <p className="text-[14px] font-medium">
                {filter === "all"
                  ? "No artifacts yet"
                  : filter === "user"
                    ? "No uploaded files yet"
                    : "No generated files yet"}
              </p>
              <p className="mx-auto mt-1 max-w-sm text-[12.5px] leading-relaxed text-muted-foreground">
                Attach files in the composer, paste large text as a file, or ask
                the agent to produce a report — everything lands here.
              </p>
            </div>
          </div>
        ) : (
          <div className="flex flex-col gap-2">
            {filtered.map((a) => {
              const Icon = kindIcon(a.kind);
              return (
                <div
                  key={a.id}
                  className="group flex items-center gap-3 rounded-xl border border-border/60 bg-card px-3.5 py-3 transition-all hover:border-border"
                >
                  <span className="flex size-9 shrink-0 items-center justify-center rounded-lg bg-secondary text-muted-foreground">
                    {a.dataUrl ? (
                      <img
                        src={a.dataUrl}
                        alt=""
                        className="size-9 rounded-lg object-cover"
                      />
                    ) : (
                      <Icon className="size-4" />
                    )}
                  </span>

                  <div className="min-w-0 flex-1 leading-tight">
                    <div className="flex items-center gap-2">
                      <span className="truncate text-[13.5px] font-medium">
                        {a.name}
                      </span>
                      <span
                        className={cn(
                          "flex shrink-0 items-center gap-1 rounded-full px-1.5 py-0.5 text-[9.5px] font-semibold uppercase tracking-wide",
                          a.origin === "user"
                            ? "bg-secondary text-muted-foreground"
                            : "bg-primary/12 text-primary",
                        )}
                      >
                        {a.origin === "user" ? (
                          <Upload className="size-2.5" />
                        ) : (
                          <Sparkles className="size-2.5" />
                        )}
                        {a.origin === "user" ? "Uploaded" : "Generated"}
                      </span>
                    </div>
                    <div className="mt-0.5 flex items-center gap-1.5 text-[11.5px] text-muted-foreground">
                      {a.kind.toUpperCase()} · {formatBytes(a.size)}
                      {a.conversationTitle && (
                        <>
                          <span aria-hidden>·</span>
                          <button
                            className="flex items-center gap-1 truncate hover:text-foreground hover:underline"
                            onClick={() => {
                              if (a.conversationId) {
                                openChat(a.conversationId);
                                useUIStore.getState().goToChat();
                              }
                            }}
                          >
                            <MessageSquare className="size-2.5 shrink-0" />
                            <span className="truncate">{a.conversationTitle}</span>
                          </button>
                        </>
                      )}
                    </div>
                  </div>

                  <div className="flex shrink-0 items-center gap-0.5">
                    <button
                      aria-label={`Preview ${a.name}`}
                      onClick={() => setArtifactPreviewId(a.id)}
                      className="rounded-lg p-2 text-muted-foreground transition-colors hover:bg-secondary hover:text-foreground"
                    >
                      <Eye className="size-4" />
                    </button>
                    <button
                      aria-label={`Download ${a.name}`}
                      onClick={() => downloadArtifact(a)}
                      className="rounded-lg p-2 text-muted-foreground transition-colors hover:bg-secondary hover:text-foreground"
                    >
                      <Download className="size-4" />
                    </button>
                    <button
                      aria-label={`Remove ${a.name}`}
                      onClick={() => {
                        removeArtifact(a.id);
                        toast.success("Artifact removed");
                      }}
                      className="rounded-lg p-2 text-muted-foreground opacity-0 transition-all hover:bg-destructive/10 hover:text-destructive group-hover:opacity-100"
                    >
                      <Trash2 className="size-4" />
                    </button>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
}
