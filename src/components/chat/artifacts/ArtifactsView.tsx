function kindIcon(kind: Artifact["kind"]) {
  switch (kind) {
    case "image":
      return ImageIcon;
    case "pdf":
      return FileUp;
    case "code":
      return FileCode2;
    case "data":
      return FileJson;
    default:
      return FileText;
  }
}

function downloadArtifact(artifact: Artifact) {
  const a = document.createElement("a");
  if (artifact.dataUrl) {
    a.href = artifact.dataUrl;
  } else if (artifact.textContent) {
    const blob = new Blob([artifact.textContent], {
      type: artifact.mime || "text/plain",
    });
    a.href = URL.createObjectURL(blob);
  } else {
    toast.info("Preview not available", {
      description: `${artifact.name} is a mock binary — download arrives with real storage.`,
    });
    return;
  }
  a.download = artifact.name;
  document.body.appendChild(a);
  a.click();
  a.remove();
}

